"""Read cash evidence from TSM's reviewed statements and October 2026 slides."""

from html import unescape
import re

from src.sec_native_quarter_tables import (
    _NativeTables, _column_value, _grid, _norm, _number, _separate_caption, _statement_columns,
)


_STATEMENT_CAPTION = ('Taiwan Semiconductor Manufacturing Company Limited and Subsidiaries '
                      'Consolidated Statements of Cash Flows (In Thousands of New Taiwan Dollars)').casefold()
_CASH_NOTE = re.compile(r'\b29\s*\.\s*CASH FLOW INFORMATION\s+a\. Non-cash transactions$', re.I)
_OPERATING = 'CASH FLOWS FROM OPERATING ACTIVITIES'
_INVESTING = 'CASH FLOWS FROM INVESTING ACTIVITIES'
_CFO = 'Net cash generated by operating activities'
_PURCHASES = 'Payments for acquisition of property, plant and equipment'
_PPE = 'Property, plant and equipment'
_PRESENTATION_SLIDE = re.compile(r'<img\s+src="a3q26presentatione008\.jpg"\s+title="slide8"[^<>]{0,250}>', re.I)
_SLIDE_TEXT = re.compile(r'\s*<div>\s*<font\b[^<>]{0,300}>([^<>]{1,900})</font>\s*</div>', re.I)
_BILLIONS = r'(?:[0-9]{1,3}(?:,[0-9]{3})+|[0-9]{1,12})\.[0-9]{2}'
_PRESENTATION_CASH = re.compile(
    rf'\bCash Flows\b.*?\(In NT\$ billions\) 3Q26 2Q26 3Q25 Beginning Balance (?:{_BILLIONS} ){{3}}'
    rf'Cash from operating activities ({_BILLIONS}) (?:{_BILLIONS} ){{2}}'
    rf'Capital expenditures \(({_BILLIONS})\) (?:\({_BILLIONS}\) ){{2}}Cash dividends\b'
)


def _single(values):
    if len(values) != 1:
        raise ValueError('TSM cash filing row or column is missing or ambiguous')
    return values[0]


def _label_index(labels, label):
    return _single([index for index, value in enumerate(labels) if value == label])


def _text(raw, limit):
    if not isinstance(raw, bytes) or not 0 < len(raw) <= limit:
        raise ValueError('TSM cash filing exceeds its size limit or is unavailable')
    return raw.decode('utf-8-sig')


def _reviewed_rows(table, period_end):
    if table['bad'] or not 1 <= len(table['rows']) <= 500:
        raise ValueError('TSM cash filing table is invalid')
    grid = _grid(table['rows'])
    if not grid:
        raise ValueError('TSM cash filing table is invalid')
    start = next((index for index, (cells, _) in enumerate(grid) if cells and cells[0]['text']), 0)
    if not 1 <= start <= 12 or any(cell['bad'] for cells, _ in grid[:start] for cell in cells):
        raise ValueError('TSM cash filing headers are invalid')
    column, width = _single([(column, width) for column, width, (kind, start_date, end, _), *_
        in _statement_columns(grid[:start], '1231') if kind == 'cumulative'
        and start_date.isoformat() == '2026-01-01' and end.isoformat() == period_end])
    return grid[start:], column, width


def _read_amount(grid, column, width, index):
    cells, _ = grid[index]
    if cells[0]['bad']:
        raise ValueError('TSM cash filing label is invalid')
    result = _number(_column_value(grid[index], width, column), 0, dollar_marker=True)
    if result is None or type(result[0]) is not int:
        raise ValueError('TSM cash filing amount is unavailable')
    return result[0]


def parse_reviewed_cash_flows(raw, *, period_end):
    """Return the two matching cumulative cash amounts in TWD thousands."""
    if period_end not in {'2026-06-30', '2026-09-30'}:
        raise ValueError('TSM cash filing period is outside the reviewed scope')
    parser = _NativeTables()
    parser.feed(_text(raw, 8 * 1024 * 1024))
    parser.close()
    operating, investing, note = [], [], []
    for index, table in enumerate(parser.tables):
        previous = parser.tables[index - 1] if index else None
        scope = table['nearby'] or _separate_caption(table, previous, parser)
        statement = scope.casefold() == _STATEMENT_CAPTION
        supplement = bool(_CASH_NOTE.search(scope))
        if not statement and not supplement:
            continue
        grid, column, width = _reviewed_rows(table, period_end)
        labels = [cells[0]['text'] if cells else '' for cells, _ in grid]
        if statement and _OPERATING in labels:
            target = _label_index(labels, _CFO)
            if _label_index(labels, _OPERATING) >= target or _INVESTING in labels[:target]:
                raise ValueError('TSM cash filing operating section is invalid')
            operating.append(_read_amount(grid, column, width, target))
        if statement and _INVESTING in labels:
            first = _label_index(labels, 'Acquisitions of:')
            last = _label_index(labels, 'Proceeds from disposal or redemption of:')
            if not _label_index(labels, _INVESTING) < first < last:
                raise ValueError('TSM cash filing acquisitions group is invalid')
            target = _single([i for i in range(first + 1, last) if labels[i] == _PPE])
            investing.append(_read_amount(grid, column, width, target))
        if supplement:
            target = _label_index(labels, _PURCHASES)
            note.append(_read_amount(grid, column, width, target))
    cfo, acquisitions, cash_payments = _single(operating), _single(investing), _single(note)
    if cfo <= 0 or cash_payments <= 0 or acquisitions != -cash_payments:
        raise ValueError('TSM cash filing purchases and Note 29 do not reconcile')
    return dict(cash_from_operations=cfo, capital_expenditures=cash_payments)


def parse_presentation_cash_flows(raw):
    """Return October presentation Q3 amounts in hundredths of a TWD billion."""
    document = _text(raw, 64 * 1024)
    slide = _single(list(_PRESENTATION_SLIDE.finditer(document)))
    transcription = _SLIDE_TEXT.match(document, slide.end())
    if not transcription:
        raise ValueError('TSM presentation cash flow rows or quarter headings are unavailable')
    evidence = _single(list(_PRESENTATION_CASH.finditer(_norm(unescape(transcription[1])))))
    cfo, acquisitions = (_number(text, 2)[0] for text in evidence.groups())
    if cfo <= 0 or acquisitions <= 0:
        raise ValueError('TSM presentation cash values are outside the reviewed scope')
    return dict(cash_from_operations=cfo, capital_expenditures=acquisitions)
