import pytest

from src.sec_tsm_cash_tables import parse_presentation_cash_flows, parse_reviewed_cash_flows


def _rows(duration, *rows):
    head = f'<tr><td></td><td colspan="3">{duration}</td></tr>'
    head += '<tr><td></td><td>2026</td><td></td><td>2025</td></tr>'
    body = ''.join(f'<tr><td>{label}</td><td>{value}</td><td></td><td>{prior}</td></tr>'
                   for label, value, prior in rows)
    return '<table>' + head + body + '</table>'


def _report(duration='Nine Months Ended September 30'):
    cash = ('<p>Taiwan Semiconductor Manufacturing Company Limited and Subsidiaries</p>'
            '<h2>Consolidated Statements of Cash Flows</h2><p>(In Thousands of New Taiwan Dollars)</p>')
    operating = _rows(duration, ('CASH FLOWS FROM OPERATING ACTIVITIES', '', ''),
                      ('Net cash generated by operating activities', '12,345', '3,331'))
    investing = _rows(duration, ('CASH FLOWS FROM INVESTING ACTIVITIES', '', ''), ('Acquisitions of:', '', ''),
                      ('Property, plant and equipment', '(4,567)', '(2,000)'),
                      ('Proceeds from disposal or redemption of:', '', ''),
                      ('Property, plant and equipment', '765', '789'))
    note = _rows(duration, ('Additions of property, plant and equipment', '5,100', '2,100'),
                 ('Payments for acquisition of property, plant and equipment', '$4,567', '$2,000'))
    return cash + operating + cash + investing + '<h2>29. CASH FLOW INFORMATION</h2><p>a. Non-cash transactions</p>' + note


def _presentation():
    return ('<img src="a3q26presentatione008.jpg" title="slide8" width="1365" height="768">'
            '<div><font size="1">TSMC Property Cash Flows * Free cash flow = Cash from operating activities '
            '&#8211; Capital expenditures (In NT$ billions) 3Q26 2Q26 3Q25 Beginning Balance 100.00 50.00 10.00 '
            'Cash from operating activities 19.23 6.34 4.56 Capital expenditures (7.89) (2.34) (3.45) '
            'Cash dividends (5.62) (2.31) (4.13)</font></div>')


@pytest.mark.parametrize(('duration', 'end'), [('Nine Months Ended September 30', '2026-09-30'),
                                                ('Six Months Ended June 30', '2026-06-30')])
def test_reviewed_cash_uses_matching_cumulative_column_and_corroborates_gross_acquisitions(duration, end):
    assert parse_reviewed_cash_flows(_report(duration).encode(), period_end=end) == {
        'cash_from_operations': 12345, 'capital_expenditures': 4567,
    }


@pytest.mark.parametrize(('before', 'after'), [
    ('Nine Months Ended September 30', 'Three Months Ended September 30'),
    ('In Thousands of New Taiwan Dollars', 'In Millions of New Taiwan Dollars'),
    ('(4,567)', '(4,568)'),
    ('(4,567)', '4,567'),
    ('Acquisitions of:', 'Proceeds from disposal or redemption of:'),
    ('Payments for acquisition of property, plant and equipment', 'Net payments for property, plant and equipment'),
    ('<h2>29. CASH FLOW INFORMATION', '<h2>19. CASH FLOW INFORMATION'),
])
def test_reviewed_cash_rejects_incompatible_scope_or_unreconciled_line(before, after):
    with pytest.raises(ValueError):
        parse_reviewed_cash_flows(_report().replace(before, after).encode(), period_end='2026-09-30')


def test_presentation_extracts_only_current_quarter_operating_cash_and_reported_capex():
    assert parse_presentation_cash_flows(_presentation().encode()) == {
        'cash_from_operations': 1923, 'capital_expenditures': 789,
    }


@pytest.mark.parametrize(('before', 'after'), [('title="slide8"', 'title="slide7"'),
                                                (' NT$ billions', ' US$ billions'),
                                                ('3Q26 2Q26 3Q25', '2Q26 3Q26 3Q25'),
                                                ('(7.89)', '7.89')])
def test_presentation_rejects_ambiguous_or_incompatible_source_rows(before, after):
    with pytest.raises(ValueError):
        parse_presentation_cash_flows(_presentation().replace(before, after).encode())
